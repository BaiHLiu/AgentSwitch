#!/usr/bin/env bash
# Regenerates the hash-pinned requirement files build-runtime.sh installs with `--require-hashes`, one per architecture:
#   python-requirements-<arch>.txt   everything packages/secret-gate needs at run time, one version each
# Versions come from packages/mac-app/scripts/python-constraints.txt (the tested set of packages/secret-gate/.venv), so a
# Linux node runs what a Mac does; mitmproxy-linux takes the place of mitmproxy-macos. Wheels only. Needs uv.
#
#   scripts/lock-python.sh    after changing the constraints, secret-gate's dependencies or the Python pin; review the
#                             diff and commit the files
set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
# shellcheck source=runtime-pins.sh
source "$HERE/scripts/runtime-pins.sh"
command -v uv >/dev/null || die "needs uv (https://docs.astral.sh/uv/)"

for platform in x86_64-manylinux_2_28 aarch64-manylinux_2_28; do
  arch="${platform%%-*}"
  out="$HERE/scripts/python-requirements-$arch.txt"
  log "$out"
  {
    echo "# Generated by scripts/lock-python.sh; do not edit by hand. build-runtime.sh installs this with"
    echo "# --require-hashes --only-binary :all: into the runtime's CPython $PYTHON_VERSION ($platform)."
    uv pip compile "$REPO/packages/secret-gate/pyproject.toml" -c "$REPO/packages/mac-app/scripts/python-constraints.txt" \
      --python-version "$PY_MINOR" --python-platform "$platform" --generate-hashes --only-binary :all: --no-header \
      --index-url https://pypi.org/simple 2>/dev/null
  } > "$out.part"
  mv "$out.part" "$out"
done
